#!/usr/bin/env python3
"""Measure the seven core skills by load class, and count checker clauses.

Usage: python3 -B artifacts/core-skills-compression-20261116/measure.py [repo-root]
Prints Markdown. Exit 0 on success, 2 when a target is missing.
"""
import ast
import sys
from pathlib import Path

SKILLS = [
    "alaa-testing-strategy",
    "alaa-cc-orchestrator",
    "alaa-codex-orchestrator",
    "alaa-workflow",
    "alaa-code-intelligence-routing",
    "alaa-low-noise",
    "alaa-prompting-guide",
]
CHECKERS = [
    "alaa-testing-strategy/scripts/check_execution_contracts.py",
    "alaa-cc-orchestrator/scripts/check_agent_contracts.py",
    "alaa-codex-orchestrator/scripts/check_agent_contracts.py",
]
TEXT = {".md", ".toml", ".json", ".yaml"}
GENERATED = "# Generated by scripts/render_agents.py"


def words(path):
    return len(path.read_text(encoding="utf-8").split())


def split_skill(skill_md):
    text = skill_md.read_text(encoding="utf-8")
    parts = text.split("---", 2)
    if len(parts) < 3:
        return 0, len(text.split())
    return len(parts[1].split()), len(parts[2].split())


def measure(root):
    rows = []
    for name in SKILLS:
        base = root / "skills" / "sohrab" / name
        if not (base / "SKILL.md").is_file():
            sys.exit(2)
        front, body = split_skill(base / "SKILL.md")
        cls = {"references": 0, "assets": 0, "agents-hand": 0, "agents-generated": 0, "other": 0}
        for path in sorted(base.rglob("*")):
            if not path.is_file() or path.suffix not in TEXT or path.name in ("SKILL.md", "CHANGELOG.md"):
                continue
            rel = path.relative_to(base).parts
            count = words(path)
            if rel[0] == "references":
                cls["references"] += count
            elif rel[0] == "assets":
                cls["assets"] += count
            elif rel[0] == "agents" and path.name != "openai.yaml":
                key = "agents-generated" if GENERATED in path.read_text(encoding="utf-8") else "agents-hand"
                cls[key] += count
            else:
                cls["other"] += count
        source = front + body + cls["references"] + cls["assets"] + cls["agents-hand"] + cls["other"]
        rows.append((name, front, body, cls, source))
    return rows


def clause_counts(root):
    out = []
    for rel in CHECKERS:
        tree = ast.parse((root / "skills" / "sohrab" / rel).read_text(encoding="utf-8"))
        for node in tree.body:
            if isinstance(node, (ast.Assign, ast.AnnAssign)) and node.value is not None:
                target = node.targets[0] if isinstance(node, ast.Assign) else node.target
                if not isinstance(target, ast.Name) or not target.id.isupper():
                    continue
                count = sum(
                    1 for sub in ast.walk(node.value)
                    if isinstance(sub, ast.Constant) and isinstance(sub.value, str)
                )
                if count:
                    out.append((rel, target.id, count))
    return out


def main():
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.cwd()
    print("| Skill | Frontmatter | SKILL.md body | References | Assets | Hand-written agents | Generated agents | Other | Source total |")
    print("|---|---|---|---|---|---|---|---|---|")
    total = 0
    for name, front, body, cls, source in measure(root):
        total += source
        print(f"| `{name}` | {front} | {body} | {cls['references']} | {cls['assets']} | {cls['agents-hand']} | {cls['agents-generated']} | {cls['other']} | {source} |")
    print(f"\nSource total, all seven skills: {total} words. Generated agents, CHANGELOG.md and scripts are excluded from it.\n")
    print("| Checker | Tuple | String constants |")
    print("|---|---|---|")
    for rel, name, count in clause_counts(root):
        print(f"| `{rel}` | `{name}` | {count} |")


if __name__ == "__main__":
    main()
