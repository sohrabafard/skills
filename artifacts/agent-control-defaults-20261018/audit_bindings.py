LINKS = {'alaa-task-hub', 'ci-image', 'wa', 'tusd', 'gateway', 'deploy', 'client'}
IMPORTS = {'skills', 'octane-base'}
START = b'<!-- BEGIN ALAA BEADS BINDING -->'
END = b'<!-- END ALAA BEADS BINDING -->'


def git(root, *args):
    result = subprocess.run(['git', '-C', str(root), *args], capture_output=True)
    if result.returncode:
        raise RuntimeError(f'{root.name}: git {args}: exit {result.returncode}: '
                           f'{result.stderr.decode("utf-8", errors="replace")}')
    if result.stderr:
        raise RuntimeError(f'{root.name}: unexpected Git diagnostic: '
                           f'{result.stderr.decode("utf-8", errors="replace")}')
    return result.stdout


def sha(data):
    return hashlib.sha256(data).hexdigest()


def split_block(data, start=START, end=END):
    assert data.count(start) == data.count(end) == 1, 'nonunique or absent markers'
    begin = data.index(start)
    finish = data.index(end) + len(end)
    assert finish > begin, 'reversed markers'
    return data[:begin], data[begin:finish], data[finish:]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--project-root', type=Path, required=True)
    parser.add_argument('--only', choices=sorted(BASES))
    parser.add_argument('--output', default='verification-bindings.json')
    args = parser.parse_args()
    output = Path(__file__).resolve().parent
    template_raw = (output / 'binding-template.md').read_bytes()
    template = template_raw.rstrip(b'\n')
    records, findings = [], []
    for name, base in BASES.items():
        if args.only and name != args.only:
            continue
        root = args.project_root / name
        try:
            head = git(root, 'rev-parse', 'HEAD').decode().strip()
            branch = git(root, 'branch', '--show-current').decode().strip()
            assert head == base, f'HEAD drift: {head}'
            assert branch == ('feat/sentry_setup' if name == 'client' else 'main'), 'branch drift'
            paths = ['AGENTS.md'] if name in LINKS | IMPORTS else ['AGENTS.md', 'CLAUDE.md']
            files = []
            for path in paths:
                current = (root / path).read_bytes()
                current.decode('utf-8', errors='strict')
                old = git(root, 'show', f'{base}:{path}')
                prefix, block, suffix = split_block(current)
                old_start, old_end = START, END
                if name == 'alaa-task-hub':
                    old_start = b'<!-- BEGIN BEADS CODEX SETUP: generated by bd setup codex -->'
                    old_end = b'<!-- END BEADS CODEX SETUP -->'
                old_prefix, _, old_suffix = split_block(old, old_start, old_end)
                assert block == template.replace(b'__PROJECT__', name.encode()), f'{path}: template mismatch'
                assert prefix == old_prefix and suffix == old_suffix, f'{path}: outside bytes changed'
                assert not current.startswith(b'\xef\xbb\xbf'), f'{path}: BOM'
                assert b'\r' not in block, f'{path}: CR in binding'
                assert not git(root, 'diff', '--cached', '--name-only', '--', path), f'{path}: staged overlap'
                files.append({'path': path, 'sha256': sha(current), 'block_sha256': sha(block),
                              'block_matches_template': True, 'outside_bytes_match_head': True})
            if name in LINKS:
                link = root / 'CLAUDE.md'
                assert link.is_symlink() and link.resolve() == (root / 'AGENTS.md').resolve(), 'link target drift'
                assert git(root, 'ls-files', '-s', '--', 'CLAUDE.md').startswith(b'120000 '), 'link mode drift'
                assert not git(root, 'diff', 'HEAD', '--', 'CLAUDE.md'), 'link bytes drift'
                assert split_block(link.read_bytes())[1] == template.replace(b'__PROJECT__', name.encode())
            elif name in IMPORTS:
                # An unchanged checkout can have CRLF while its Git blob has LF.
                # Compare through Git's configured clean conversion, preserve raw bytes.
                assert git(root, 'hash-object', '--path=CLAUDE.md', 'CLAUDE.md').strip() == git(root, 'rev-parse', f'{base}:CLAUDE.md').strip(), 'import content drift'
                assert not git(root, 'diff', 'HEAD', '--', 'CLAUDE.md'), 'import Git drift'
            git(root, 'diff', '--check', '--', 'AGENTS.md', 'CLAUDE.md')
            status = git(root, 'status', '--porcelain=v1', '-z', '--untracked-files=no')
            dirty = []
            for entry in filter(None, status.split(b'\0')):
                state, path = entry[:2].decode(), entry[3:].decode('utf-8')
                assert not any(c in state for c in 'RC'), 'unexpected rename/copy requires manual reconciliation'
                dirty.append({'status': state, 'path': path,
                              'index_entry': git(root, 'ls-files', '-s', '--', path).decode().strip(),
                              'sha256': sha((root / path).read_bytes())})
            if name not in {'skills', 'deploy'}:
                assert {d['path'] for d in dirty} == set(paths), 'unexpected tracked dirty scope'
            staged_unrelated = git(root, 'diff', '--cached', '--binary', '--', '.',
                                   *[f':(exclude){p}' for p in paths])
            records.append({'name': name, 'base_head': base, 'branch': branch, 'files': files,
                            'unchanged_import_sha256': sha((root / 'CLAUDE.md').read_bytes()) if name in IMPORTS else None,
                            'unrelated_tracked': [d for d in dirty if d['path'] not in paths],
                            'staged_unrelated_sha256': sha(staged_unrelated),
                            'untracked_paths': git(root, 'ls-files', '--others', '--exclude-standard').decode().splitlines()})
            print(f'{name}: PASS ({len(files)} physical files)', flush=True)
        except Exception as exc:
            findings.append(f'{name}: {exc}')
            print(f'{name}: FAIL: {exc}', flush=True)
    covered_links = len(set(r['name'] for r in records) & LINKS)
    covered_imports = len(set(r['name'] for r in records) & IMPORTS)
    manifest = {'generated_utc': datetime.now(timezone.utc).isoformat(),
                'source_template_sha256': sha(template_raw), 'repositories': records,
                'counts': {'repositories': len(records), 'physical_changed_binding_files': sum(len(r['files']) for r in records),
                           'logical_binding_paths': sum(len(r['files']) for r in records) + covered_links,
                           'preserved_symlinks': covered_links, 'unchanged_imports': covered_imports},
                'findings': findings}
    (output / args.output).write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8', newline='\n')
    print(json.dumps(manifest['counts']))
    return int(bool(findings) or len(records) != (1 if args.only else 17))


if __name__ == '__main__':
    raise SystemExit(main())
