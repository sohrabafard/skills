#!/usr/bin/env python3
"""Render reviewer wrappers and the source manifest. Exit 0 clean, 1 drift, 2 error."""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
REVIEWERS = ("alaa-reviewer", "alaa-reviewer-deep")


def owner_module(name: str, policy_root: Path | None = None):
    """Load a dependency from the selected canonical owner, never a cached sibling."""
    owner = policy_root or ROOT.parent / "alaa-prompting-guide"
    spec = importlib.util.spec_from_file_location(name, owner / "scripts" / f"{name}.py")
    if spec is None or spec.loader is None:
        raise ValueError("canonical policy loader unavailable")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def policy_api(policy_root: Path | None = None):
    owner = policy_root or ROOT.parent / "alaa-prompting-guide"
    controls = owner_module("task_model_controls", owner)
    previous = sys.modules.get("task_model_controls")
    sys.modules["task_model_controls"] = controls
    try:
        module = owner_module("codex_model_policy", owner)
    finally:
        if previous is None:
            sys.modules.pop("task_model_controls", None)
        else:
            sys.modules["task_model_controls"] = previous
    return module, module.load_policy(owner / "assets" / "codex-model-policy.json")


def reviewer_text(name: str, body: str, policy: dict) -> str:
    description = (
        "Fresh-context independent read-only reviewer for complete orchestrated changes or "
        "user-authored work. Judges correctness, regressions, security, tests, and production "
        "risks. Never edits or fixes."
    )
    if name == "alaa-reviewer-deep":
        description = (
            "Deep correctness-review profile for complex subsystem interactions, broad failure "
            "impact, or documented insufficiency of standard review. Select instead of "
            "alaa-reviewer for the same scope. Same independent review contract; never edits."
        )
    return (
        "# Generated by scripts/render_agents.py; edit assets/reviewer-contract.md.\n"
        f'name = "{name}"\n'
        f'description = "{description}"\n'
        'sandbox_mode = "read-only"\n'
        "# grant-template: materialize-live-parent-mcp\n\n"
        'developer_instructions = ' + json.dumps(body, ensure_ascii=False) + '\n'
    )


def expected_outputs(root: Path, policy: dict, policy_root: Path | None = None) -> dict[Path, bytes]:
    projection = owner_module("profile_projection", policy_root)
    body = (root / "assets" / "reviewer-contract.md").read_text(encoding="utf-8")
    wrappers = {
        root / "agents" / f"{name}.toml": reviewer_text(name, body, policy).encode("utf-8")
        for name in REVIEWERS
    }
    wrappers.update(projection.expected_profiles(root, policy, "toml"))
    agents = {path: path.read_bytes() for path in sorted((root / "agents").glob("*.toml"))}
    agents.update(wrappers)
    agents = {path: projection.neutral_agent_text("toml", data.decode("utf-8"),
              policy["profiles"][path.stem]).encode("utf-8")
              for path, data in agents.items()}
    manifest = {
        "pack": "alaa-codex-orchestrator",
        "version": (root / "VERSION").read_text(encoding="utf-8").strip(),
        "managed_agents": [
            {"name": path.stem, "file": path.relative_to(root).as_posix(),
             "sha256": hashlib.sha256(data).hexdigest()}
            for path, data in sorted(agents.items())
        ],
    }
    return {**agents, root / "assets" / "manifest.json":
            (json.dumps(manifest, indent=2) + "\n").encode("utf-8")}


def drift(outputs: dict[Path, bytes]) -> list[Path]:
    return [path for path, data in outputs.items()
            if not path.is_file() or path.read_bytes() != data]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    parser.add_argument("--policy-root", type=Path)
    args = parser.parse_args()
    try:
        _, policy = policy_api(args.policy_root)
        outputs = expected_outputs(ROOT, policy, args.policy_root)
        changed = drift(outputs)
        if args.check and changed:
            for path in changed:
                print(f"generated drift: {path.relative_to(ROOT)}", file=sys.stderr)
            return 1
        if args.write:
            for path in changed:
                path.write_bytes(outputs[path])
        print(f"RENDER {'CHECK' if args.check else 'WRITE'} OK: {len(outputs)} generated files")
        return 0
    except (OSError, ValueError, KeyError, AssertionError) as exc:
        print(f"render error: {exc}", file=sys.stderr)
        return 2 if not isinstance(exc, AssertionError) else 1


if __name__ == "__main__":
    raise SystemExit(main())
